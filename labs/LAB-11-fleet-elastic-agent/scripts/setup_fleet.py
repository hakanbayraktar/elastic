#!/usr/bin/env python3
"""LAB-11 Adim 1-2'nin betik karsiligi: Kibana arayuzunde yapilanlari API ile yapar ve .env dosyasini yazar.

Arayuzle ayni sonucu verir (sonraki adimlarin komutlari ve ciktilari degismez):
  1. Fleet output'u: http://elasticsearch-lab00:9200 (Settings > Outputs > default).
  2. Fleet Server (Quick Start'in yaptigi): "Lab Fleet Server" adresi https://fleet-server:8220,
     "Fleet Server Policy" (id fleet-server-policy, System + Fleet Server integration'lari), service token.
  3. "Lab Linux sunucu" politikasi: namespace fleetlab, ajan izleme kapali, System integration'i
     system-lab adiyla ve Proc Filesystem Directory /hostfs ile.
  4. Bu politikanin enrollment token'i.
Iki token .env dosyasina yazilir, ekrana basilmaz.
"""
import base64
import json
import os
import urllib.error
import urllib.request

ES = os.environ.get("ES_URL", "http://127.0.0.1:9200")
KB = os.environ.get("KIBANA_URL", "http://127.0.0.1:5601")
AUTH = "Basic " + base64.b64encode(b"elastic:DevOps2026!").decode()
POLITIKA = "Lab Linux sunucu"


def api(path, method="GET", body=None):
    req = urllib.request.Request(KB + path, method=method, data=json.dumps(body).encode() if body is not None else None)
    req.add_header("Authorization", AUTH)
    req.add_header("Content-Type", "application/json")
    req.add_header("kbn-xsrf", "true")
    try:
        with urllib.request.urlopen(req, timeout=180) as r:
            return r.status, json.loads(r.read() or b"{}")
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b"{}")


def surum(paket):
    return api(f"/api/fleet/epm/packages/{paket}")[1]["item"]["latestVersion"]


api("/api/fleet/setup", "POST")
api("/api/fleet/outputs/fleet-default-output", "PUT", {"hosts": ["http://elasticsearch-lab00:9200"]})
print("output                 : http://elasticsearch-lab00:9200")

hosts = api("/api/fleet/fleet_server_hosts")[1].get("items", [])
if not any("https://fleet-server:8220" in h.get("host_urls", []) for h in hosts):
    api("/api/fleet/fleet_server_hosts", "POST",
        {"name": "Lab Fleet Server", "host_urls": ["https://fleet-server:8220"], "is_default": True})
print("fleet server adresi    : https://fleet-server:8220")

for paket in ("fleet_server", "system"):
    api(f"/api/fleet/epm/packages/{paket}/{surum(paket)}", "POST")
# Quick Start'in actigi politika (System integration'i ile); README 1.3'teki gibi ajan izleme kapali
api("/api/fleet/agent_policies?sys_monitoring=true", "POST", {
    "id": "fleet-server-policy", "name": "Fleet Server Policy", "namespace": "default",
    "description": "Fleet Server policy generated by Kibana", "has_fleet_server": True,
    "is_default_fleet_server": True, "monitoring_enabled": []})
servis = api("/api/fleet/service_tokens", "POST", {})[1].get("value")
print("Fleet Server politikasi: Fleet Server Policy (fleet-server-policy), service token " + ("alindi" if servis else "YOK"))

durum, cevap = api("/api/fleet/agent_policies", "POST",
                   {"name": POLITIKA, "namespace": "fleetlab", "monitoring_enabled": []})
pid = cevap.get("item", {}).get("id")
# system.hostfs: ajan container'da calisir; sunucunun /proc'u /hostfs/proc'a baglanir (docker-compose.yml)
api("/api/fleet/package_policies", "POST", {
    "name": "system-lab", "policy_id": pid,
    "package": {"name": "system", "version": surum("system")},
    "inputs": {"system-system/metrics": {"vars": {"system.hostfs": "/hostfs"}}}})
print(f"Linux politikasi       : {POLITIKA} (namespace fleetlab, system-lab, hostfs=/hostfs)")

anahtarlar = api("/api/fleet/enrollment_api_keys?perPage=100")[1].get("items", [])
kayit = next((a["api_key"] for a in anahtarlar if a.get("policy_id") == pid and a.get("active")), None)
print("enrollment token       : " + ("alindi" if kayit else "YOK"))

yol = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".env")
fd = os.open(yol, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write(f"FLEET_SERVER_SERVICE_TOKEN={servis}\nFLEET_ENROLLMENT_TOKEN={kayit}\n")
print(".env                   : yazildi")
